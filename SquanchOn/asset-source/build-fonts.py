def outline(operations):
    """Pen operations as closed contours of (start, control or None, end) segments."""
    contours, current, start = [], None, None
    for operator, points in operations:
        if operator == 'moveTo':
            start = current = points[0]
            contours.append([])
        elif operator == 'lineTo':
            contours[-1].append((current, None, points[0]))
            current = points[0]
        elif operator == 'qCurveTo':
            if points[-1] is None:  # no point on the curve: start halfway between two controls
                first, last = points[0], points[-2]
                start = current = ((first[0] + last[0]) / 2, (first[1] + last[1]) / 2)
                contours.append([])
                points = points[:-1] + (start,)
            for control, point in decomposeQuadraticSegment(points):
                contours[-1].append((current, control, point))
                current = point
        elif current != start:
            contours[-1].append((current, None, start))
            current = start
    return [contour for contour in contours if contour]


def clockwise(contours):
    area = 0.0
    for contour in contours:
        for a, control, b in contour:
            for p, q in ((a, control), (control, b)) if control else ((a, b),):
                area += p[0] * q[1] - q[0] * p[1]
    return area < 0


def thicken(contours, across, along):
    """Move every outline point outwards along its corner's bisector."""
    side = 1 if clockwise(contours) else -1  # ink lies to the right of a clockwise outline
    result = []
    for contour in contours:
        ring = []
        for _, control, end in contour:
            ring += ([control] if control else []) + [end]
        moved = []
        for index, point in enumerate(ring):
            units = []
            for step in (-1, 1):
                other = index
                for _ in ring:
                    other = (other + step) % len(ring)
                    dx, dy = (ring[other][0] - point[0]) * step, (ring[other][1] - point[1]) * step
                    if math.hypot(dx, dy) > 1e-6:
                        break
                length = math.hypot(dx, dy) or 1.0
                units.append((dx / length, dy / length))
            (ux, uy), (vx, vy) = units
            nx, ny = -(uy + vy), ux + vx
            length = math.hypot(nx, ny)
            nx, ny = (nx / length, ny / length) if length > 1e-6 else (-uy, ux)
            reach = 1 / max(nx * -uy + ny * ux, 0.5)
            moved.append((point[0] + side * nx * reach * across, point[1] + side * ny * reach * along))
        rebuilt, current, index = [], moved[-1], 0
        for _, control, _ in contour:
            if control:
                rebuilt.append((current, moved[index], moved[index + 1]))
                index += 1
            else:
                rebuilt.append((current, None, moved[index]))
            current = moved[index]
            index += 1
        result.append(rebuilt)
    return result


def bolt(left, right, top, tip, teeth=3, zig=0.8, rise=0.5, taper=0.5, drift=0.0, flip=False):
    """A jagged terminal for a stem cut at `top` between `left` and `right`, ending in a point at height `tip`.

    The stroke runs down leaning one way, jumps back sideways (`zig`, a share of its width there) and up
    (`rise`, a share of that jump) at each tooth, and narrows by `taper` to a point `drift` beside the stem's
    middle. Returns the points from the left edge of the cut round to the right edge.
    """
    width, middle = right - left, (left + right) / 2
    shares = [1.0] * (teeth - 1) + [1.5]
    lengths, jumps, total = [], [], top - tip
    for _ in range(8):  # the jumps lengthen the path, which moves the jumps: settle
        lengths = [total * share / sum(shares) for share in shares]
        run, halves = 0.0, []
        for length in lengths:
            run += length
            halves.append(width / 2 * max(1 - run / total, 0) ** taper)
        jumps = [zig * 2 * half for half in halves[:-1]]
        total = top - tip + sum(rise * jump for jump in jumps)
    slant = (sum(jumps) - drift) / total
    x, y, edge_left, edge_right = middle, top, [], []
    for index, length in enumerate(lengths):
        x, y, half = x - slant * length, y - length, halves[index]
        edge_left.append((x - half, y))
        edge_right.append((x + half, y))
        if index < teeth - 1:
            x, y = x + jumps[index], y + rise * jumps[index]
            edge_left.append((x - half, y))
            edge_right.append((x + half, y))
    points = edge_left[:-1] + [(x, y)] + edge_right[-2::-1]
    if flip:
        points = [(2 * middle - px, py) for px, py in reversed(points)]
    return points


def split(segment, height):
    """Cut one segment where it crosses the horizontal line at `height`."""
    a, control, b = segment
    if control is None:
        if (a[1] - height) * (b[1] - height) >= 0:
            return [segment]
        t = (height - a[1]) / (b[1] - a[1])
        middle = (a[0] + (b[0] - a[0]) * t, height)
        return [(a, None, middle), (middle, None, b)]
    qa, qb, qc = a[1] - 2 * control[1] + b[1], 2 * (control[1] - a[1]), a[1] - height
    if abs(qa) < 1e-9:
        roots = [-qc / qb] if abs(qb) > 1e-9 else []
    else:
        root = qb * qb - 4 * qa * qc
        roots = [(-qb - s * math.sqrt(root)) / (2 * qa) for s in (1, -1)] if root > 0 else []
    pieces, start, rest = [], 0.0, segment
    for t in sorted(t for t in roots if 1e-6 < t < 1 - 1e-6):
        a, control, b = rest
        u = (t - start) / (1 - start)
        first = (a[0] + (control[0] - a[0]) * u, a[1] + (control[1] - a[1]) * u)
        second = (control[0] + (b[0] - control[0]) * u, control[1] + (b[1] - control[1]) * u)
        middle = (first[0] + (second[0] - first[0]) * u, height)
        pieces.append((a, first, middle))
        start, rest = t, (middle, second, b)
    return pieces + [rest]


def upend(contours, way):
    return [[tuple(p and (p[0], p[1] * way) for p in segment) for segment in contour] for contour in contours]


def terminal(contours, stem, height, make, limit=240):
    """Replace what hangs below `height` on one stem by the points `make(left, right)` returns."""
    turn = 1 if clockwise(contours) else -1
    contours = [[piece for segment in contour for piece in split(segment, height)] for contour in contours]
    hanging = []
    for number, contour in enumerate(contours):
        below = [((a[1] + b[1]) / 2 if c is None else (a[1] + 2 * c[1] + b[1]) / 4) < height for a, c, b in contour]
        if all(below) or not any(below):
            continue
        first = next(i for i in range(len(contour)) if below[i] and not below[i - 1])
        index = first
        while True:
            last = index
            while below[(last + 1) % len(contour)]:
                last = (last + 1) % len(contour)
            enter, leave = contour[index][0][0], contour[last][2][0]
            if (enter - leave) * turn > 0:  # ink, not a counter, lies between the crossings
                hanging.append((min(enter, leave), max(enter, leave), number, index, last))
            index = (last + 1) % len(contour)
            while not below[index]:
                index = (index + 1) % len(contour)
            if index == first:
                break
    if not -len(hanging) <= stem < len(hanging):
        raise ValueError('no stem %d at height %s: %d found' % (stem, height, len(hanging)))
    left, right, number, index, last = sorted(hanging)[stem]
    if right - left > limit:
        raise ValueError('cut at %s crosses %d units of ink, more than a stem' % (height, right - left))
    contour = contours[number]
    points = make(left, right)
    if contour[index][0][0] > contour[last][2][0]:
        points = points[::-1]
    points = [contour[index][0]] + points + [contour[last][2]]
    fresh = [(a, None, b) for a, b in zip(points, points[1:])]
    if index <= last:
        contour[index:last + 1] = fresh
    else:
        contours[number] = fresh + contour[last + 1:index]
    return contours



def top(glyphs, name):
    pen = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(pen)
    return max(p[1] for _, pts in pen.value for p in pts if p is not None)


def build(face, source, target):
    font = TTFont(source)
    if 'fvar' in font:
        axes = {axis.axisTag: axis.defaultValue for axis in font['fvar'].axes}
        axes.update(face['axes'] or {})
        instancer.instantiateVariableFont(font, axes, inplace=True)
    for table in font['cmap'].tables:
        for char, name in face.get('glyphs', {}).items():
            table.cmap[ord(char)] = name
    cmap = font.getBestCmap()
    glyphs, hmtx, glyf = font.getGlyphSet(), font['hmtx'], font['glyf']
    width = {name: hmtx[name][0] for name in font.getGlyphOrder()}
    ky = face['cap'] / top(glyphs, cmap[ord('H')])
    wanted = {chr(32 + i): value for i, value in enumerate(face['adv']) if value is not None}
    overall = sum(wanted[c] for c in SAMPLE) / sum(width[cmap[ord(c)]] * ky for c in SAMPLE)
    kx = ky * overall
    # Lowercase heights: the x-height and ascender move separately from the capitals.
    xh0, asc0 = top(glyphs, cmap[ord('x')]) * ky, top(glyphs, cmap[ord('l')]) * ky
    xh1, asc1 = (xh0, asc0) if face.get('caps') else (face['xh'], face['asc'])

    def lower(y):
        if y <= 0:
            return y
        if y <= xh0:
            return y * xh1 / xh0
        return xh1 + (y - xh0) * (asc1 - xh1) / (asc0 - xh0)

    codes = {}
    for code, name in sorted(cmap.items()):
        codes.setdefault(name, code)
    redraw = REDRAW if face.get('redraw') else None

    def shape(name, char):
        """The base drawing with its strokes thickened, as pen operations in upstream units."""
        record = DecomposingRecordingPen(glyphs)
        glyphs[name].draw(record)
        across, along = redraw['weight'].get(unicodedata.category(char) if char else '', (0, 0))
        operations = []
        for contour in thicken(outline(record.value), across / kx, along / ky):
            operations.append(('moveTo', (contour[0][0],)))
            operations += [('lineTo', (end,)) if control is None else ('qCurveTo', (control, end))
                           for _, control, end in contour]
            operations.append(('closePath', ()))
        return operations

    def stretch(root, small):
        """Where a height of the scaled base drawing goes for this letter."""
        if root in redraw['stand']:
            ys = [p[1] * ky for _, points in shape(cmap[ord(root)], root) for p in points]
            low, high = redraw['stand'][root]
            return lambda y: low + (y - min(ys)) * (high - low) / (max(ys) - min(ys))
        lift, squeeze = redraw['small'] if small else (0, 1)
        return lambda y: lift + y * squeeze
    rebuilt, metrics = {}, {}
    for name in font.getGlyphOrder():
        code = codes.get(name)
        char = chr(code) if code is not None else ''
        root = unicodedata.normalize('NFD', char)[:1]
        capital = cmap.get(ord(char.upper())) if face.get('caps') and len(char.upper()) == 1 else None
        drawn = capital or name
        record = DecomposingRecordingPen(glyphs)
        glyphs[drawn].draw(record)
        if redraw:
            record.value = shape(drawn, char)
        xs = [p[0] for _, points in record.value for p in points if p is not None]
        factor, advance = kx, width[drawn] * kx
        shift = 0.0
        if root in wanted and width[drawn]:
            base = cmap[ord(root.upper() if capital else root)]
            flex = face.get('flex', FLEX)
            share = wanted[root] / width[base]
            factor = min(max(share, kx * (1 - flex)), kx * (1 + flex))
            if root == char or width[drawn] == width[base]:
                advance = wanted[root]
            else:
                advance = width[drawn] * factor
            left, right = (min(xs), width[drawn] - max(xs)) if xs else (0, 0)
            if xs and left >= 0 and right >= 0:
                # Keep the drawing inside its new width and split the rest as upstream did.
                ink = max(xs) - min(xs)
                factor = min(factor, advance * 0.96 / ink) if ink else factor
                spare = advance - ink * factor
                shift = (spare * left / (left + right) if left + right else spare / 2) - left * factor
            else:
                shift = (advance - width[drawn] * factor) / 2
        small = char != '' and unicodedata.category(char) == 'Ll' and not face.get('caps')

        def place(point):
            if point is None:
                return None
            x, y = point[0] * factor + shift, point[1] * ky
            if small:
                y = lower(y)
            return round(x), round(y)

        pen = TTGlyphPen(None)
        if redraw:
            stand, lean = stretch(root, small), 0.0
            if char and unicodedata.category(char)[0] == 'L':
                lean = math.tan(math.radians(redraw['lean'] * ((zlib.crc32(root.encode()) % 201) / 100 - 1)))
            contours = [[tuple(p and (p[0] * factor + shift, stand(p[1] * ky)) for p in segment)
                         for segment in contour] for contour in outline(record.value)]
            for stem, cut, tip, options in redraw['bolts'].get(root, ()):
                way = 1 if tip < cut else -1  # a bolt that points up is made upside down
                contours = upend(terminal(upend(contours, way), stem, cut * way,
                                          lambda a, b: bolt(a, b, cut * way, tip * way, **options)), way)
            for stem, cut, tip, reach in redraw['spikes'].get(root, ()):
                way = 1 if tip < cut else -1
                contours = upend(terminal(upend(contours, way), stem, cut * way,
                                          lambda a, b: [(a + (b - a) * reach, tip * way)]), way)
            for contour in contours:
                contour = [tuple(p and (round(p[0] + (p[1] - face['xh'] / 2) * lean), round(p[1])) for p in segment)
                           for segment in contour]
                pen.moveTo(contour[0][0])
                for start, control, end in contour:
                    if control is not None and redraw['facet']:  # chiselled: two flats instead of an arc
                        pen.lineTo((round((start[0] + 2 * control[0] + end[0]) / 4),
                                    round((start[1] + 2 * control[1] + end[1]) / 4)))
                    pen.lineTo(end)
                pen.closePath()
        else:
            for operator, points in record.value:
                getattr(pen, operator)(*[place(p) for p in points])
        glyph = pen.glyph()
        rebuilt[name] = glyph
        left = int(glyph.coordinates.calcBounds()[0]) if glyph.numberOfContours > 0 else 0
        metrics[name] = (round(advance), left)
    for name, glyph in rebuilt.items():
        glyf[name] = glyph
        hmtx[name] = metrics[name]

    for tag in DROP:
        if tag in font:
            del font[tag]
    for tag in ('GPOS',):
        if tag in font:
            Scaler(kx, ky).visit(font[tag].table)
    if 'kern' in font:
        for table in font['kern'].kernTables:
            for pair in table.kernTable:
                table.kernTable[pair] = round(table.kernTable[pair] * kx)
    gasp = font['gasp'] = newTable('gasp')
    gasp.gaspRange = {0xFFFF: 0x000A}
    head, hhea, os2, post = font['head'], font['hhea'], font['OS/2'], font['post']
    head.unitsPerEm = 1000
    head.flags &= ~0x0018
    hhea.ascent, hhea.descent, hhea.lineGap = face['hhea']
    os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap = face['typo']
    os2.usWinAscent, os2.usWinDescent = face['win']
    os2.fsSelection &= ~0x0080  # line spacing follows hhea, as measured
    os2.fsType = 0
    os2.achVendID = 'NONE'
    if os2.version >= 2:
        os2.sxHeight, os2.sCapHeight = face['xh'], face['cap']
    for field in ('ySubscriptXSize', 'ySubscriptYSize', 'ySubscriptXOffset', 'ySubscriptYOffset',
                  'ySuperscriptXSize', 'ySuperscriptYSize', 'ySuperscriptXOffset', 'ySuperscriptYOffset',
                  'yStrikeoutSize', 'yStrikeoutPosition'):
        setattr(os2, field, round(getattr(os2, field) * ky))
    os2.xAvgCharWidth = round(sum(m[0] for m in metrics.values()) / len(metrics))
    post.underlinePosition = round(post.underlinePosition * ky)
    post.underlineThickness = round(post.underlineThickness * ky)

    names = font['name']
    copyright = names.getDebugName(0) or ''
    version = (names.getDebugName(5) or '').split(';')[0]
    names.names = []
    family, postscript = face['family'], face['family'].replace(' ', '') + '-Regular'
    release = face.get('version', '1.000')
    for identifier, text in (
        (0, copyright + ' Modified version Copyright 2026 The Squanch-On contributors.'),
        (1, family), (2, 'Regular'), (3, postscript + ';' + release), (4, family), (5, 'Version ' + release),
        (6, postscript),
        (10, 'Modified version of %s (%s): %soutlines rescaled and respaced, hinting removed, renamed. '
             'See FONTLOG.txt.' % (face['base'], version, face['note'] + '; ' if 'note' in face else '')),
        (13, OFL), (14, 'https://openfontlicense.org'),
    ):
        names.setName(text, identifier, 3, 1, 0x409)
        names.setName(text, identifier, 1, 0, 0)
    head.fontRevision = float(release)
    head.modified = head.created  # reproducible
    font.recalcTimestamp = False
    font.save(target)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('outdir')
