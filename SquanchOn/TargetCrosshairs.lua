local function learnedSpell(baseID)
  local book = C_SpellBook
  if not (book and book.FindSpellBookSlotForSpell and Enum and Enum.SpellBookSpellBank) then return end
  local effective = publicQuery(C_Spell and C_Spell.GetOverrideSpell, baseID, 0, true) or baseID
  local name = publicQuery(C_Spell and C_Spell.GetSpellName, effective)
  if type(name) ~= "string" then return end
  -- Future, hidden/replaced and inactive-spec entries must not authorize a cue.
  local ok, slot, bank = pcall(book.FindSpellBookSlotForSpell, name, false, false, false, false)
  if not ok or (issecretvalue and (issecretvalue(slot) or issecretvalue(bank)))
    or type(slot) ~= "number" or bank ~= Enum.SpellBookSpellBank.Player then return end
  local info = publicQuery(book.GetSpellBookItemInfo, slot, bank)
  if type(info) ~= "table" then return end
  local spellID = publicQuery(function() return info.spellID end)
  if type(spellID) ~= "number"
    or publicQuery(function() return info.isPassive end) ~= false
    or publicQuery(function() return info.isOffSpec end) ~= false
    or publicQuery(book.IsSpellKnown, spellID, bank) ~= true then return end
  return {slot = slot, bank = bank, spellID = spellID, name = name}
end

local function knownRanges()
  if learnedRanges then return learnedRanges end
  local _, class = UnitClass("player")
  local ranges = {ranged = {}, healing = {}, petHealing = {}}
  for kind, catalog in pairs({ranged = rangedFamilies, healing = healingFamilies, petHealing = petHealingFamilies}) do
    for _, spellID in ipairs(catalog[class] or {}) do
      local learned = learnedSpell(spellID)
      if learned then ranges[kind][#ranges[kind] + 1] = learned end
    end
  end
  learnedRanges = ranges
  return ranges
end

local function knownRange(kind)
  local answer
  for _, spell in ipairs(knownRanges()[kind]) do
    local result
    if C_SpellBook and C_SpellBook.IsSpellBookItemInRange then
      result = publicQuery(C_SpellBook.IsSpellBookItemInRange, spell.slot, spell.bank, "target")
    elseif C_Spell and C_Spell.IsSpellInRange then
      result = publicQuery(C_Spell.IsSpellInRange, spell.spellID, "target")
    else
      result = publicQuery(_G.IsSpellInRange, spell.name, "target")
    end
    -- An invalid/restricted result does not become an interaction-distance check.
    if result == true or result == 1 then return true end
    if result == false or result == 0 then answer = false end
  end
  return answer
end

local function healingRange()
  if publicQuery(UnitCanAssist, "player", "target") ~= true
    or publicQuery(UnitIsDeadOrGhost, "target") ~= false then return false end
  if knownRange("healing") then return true end
  return publicQuery(UnitIsUnit, "target", "pet") == true and knownRange("petHealing")
end

local function meleeRange()
  -- Forever's queued Raptor Strike reports true even at Auto Shot distance;
  -- melee Auto Attack has no range verdict. The shared Range module answers
  -- from the five-yard hostile check; no answer leaves these markers hidden.
  local range = suite.Range
  return range ~= nil and range:Melee("target") == true
end

-- Melee has priority: Auto Shot's minimum range must not hide melee artwork.
-- Check actual abilities, independently of cooldown/resources/proc readiness.
local function targetRangeMode()
  local _, class = UnitClass("player")
  local attackable = publicQuery(UnitCanAttack, "player", "target")
  local dead = publicQuery(UnitIsDead, "target")
  if (attackable ~= true and attackable ~= 1) or (dead ~= false and dead ~= 0) then return end
  if meleeRange() then return "melee" end
  if class == "HUNTER" then
    if spellRange(75, "Auto Shot") then return "ranged" end
  elseif knownRange("ranged") then return "ranged" end
end

local function plainFraction()
  local ok, hp = pcall(UnitHealth, "target")
  local fine, maximum = pcall(UnitHealthMax, "target")
  if not (ok and fine) or (issecretvalue and (issecretvalue(hp) or issecretvalue(maximum))) then return end
  if type(hp) == "number" and type(maximum) == "number" and maximum > 0 then
    return math.min(1, math.max(0, hp / maximum))
  end
end

-- Full health shows the given colour (white unless told otherwise).
local function rgbAt(fraction, red, green, blue)
  if fraction <= 0.20 then return 1, 0, 0 end
  if fraction < 0.35 then return 1, (fraction - 0.20) / 0.30, 0 end
  if fraction <= 0.65 then return 1, 0.5, 0 end
  local blend = (fraction - 0.65) / 0.35
  return 1 + ((red or 1) - 1) * blend, 0.5 + ((green or 1) - 0.5) * blend, (blue or 1) * blend
end

local function colorCurve(red, green, blue)
  local curve = C_CurveUtil.CreateColorCurve()
  curve:SetType(Enum.LuaCurveType.Linear)
  for _, point in ipairs({{0, 1, 0, 0}, {0.20, 1, 0, 0},
    {0.35, 1, 0.5, 0}, {0.65, 1, 0.5, 0}, {1, red, green, blue}}) do
    curve:AddPoint(point[1], CreateColor(point[2], point[3], point[4], 1))
  end
  return curve
end

local function healthMaps(cutoff)
  if not (C_CurveUtil and C_CurveUtil.CreateCurve and C_CurveUtil.CreateColorCurve
    and UnitHealthPercent and CreateColor and Enum and Enum.LuaCurveType) then return end
  local ok, maps = pcall(function()
    local result = { color = colorCurve(1, 1, 1) }
    result.guides, result.execute = C_CurveUtil.CreateCurve(), C_CurveUtil.CreateCurve()
    result.guides:SetType(Enum.LuaCurveType.Step)
    result.execute:SetType(Enum.LuaCurveType.Step)
    result.guides:AddPoint(0, 0)
    if cutoff > 0 then result.guides:AddPoint(0.0001, 0.75) end
    if cutoff < 1 then result.guides:AddPoint(math.max(0.0001, cutoff + 0.0001), 0.05) end
    result.guides:AddPoint(1, 0)
    result.execute:AddPoint(0, 0)
    result.execute:AddPoint(0.0001, 1)
    result.execute:AddPoint(math.min(1, cutoff + 0.0001), 0)
    return result
  end)
  if ok then return maps end
end

function suite:InitializeTargetCrosshairs(database, legacy)
  if self.TargetCrosshairs then return self.TargetCrosshairs end
  assert(type(database) == "table", "Target crosshairs requires the suite database")
  if type(database.targetCrosshairs) ~= "table" then
    database.targetCrosshairs = type(legacy) == "table" and duplicate(legacy) or {}
    database.targetCrosshairsMigration = type(legacy) == "table" and "CrosshairsDB" or "defaults"
  end
  local settings = database.targetCrosshairs
  for key, value in pairs(baseline) do
    if settings[key] == nil then settings[key] = value end
  end

  -- HealthRGB: the plain-number form of the health colour curve (previews).
  local marker = { db = settings, inRange = false, HealthRGB = rgbAt }
  self.TargetCrosshairs = marker
  local artwork = "Interface\\AddOns\\" .. addonName .. "\\media\\Crosshairs\\"
  local display = CreateFrame("Frame", "SQMSTargetCrosshairsFrame", WorldFrame)
  display:SetFrameStrata("BACKGROUND")
  display:SetFrameLevel(1)
  display:EnableMouse(false)
  display:Hide()

  -- A nameplate's own art is drawn with its plate, beneath frames that merely
  -- share its strata. To sit BEHIND the bar, name and icons the marker is
  -- nested in the selected Squanch-On plate at the plate's base level; its
  -- scale and alpha stay its own.
  local anchored, fitted, baseSize, bound
  local nestedIn
  -- The client's enlargement of the selected plate. Read once and kept: the
  -- CVar is re-read after a target change and the events that can change it.
  local grownScale
  local function selectedScale()
    if not grownScale then grownScale = tonumber(GetCVar and GetCVar("nameplateSelectedScale")) or 1 end
    return grownScale
  end
  marker.SelectedScale = selectedScale
  function marker:ScaleChanged() grownScale = nil end
  -- The configured ring size is in screen terms; inside a plate it is restated
  -- in the plate's units, before the client's enlargement of the selected plate.
  local function plainSize()
    if not nestedIn then return baseSize end
    local world, ui = WorldFrame:GetEffectiveScale(), UIParent:GetEffectiveScale()
    local grown = selectedScale()
    if not (world and ui and ui > 0 and grown > 0) then return baseSize end
    return baseSize * world / ui / grown
  end
  local function sink(level, fixed, ...)
    for index = 1, select("#", ...) do
      local frame = select(index, ...)
      if frame.SetFixedFrameLevel then frame:SetFixedFrameLevel(fixed) end
      frame:SetFrameLevel(level)
      sink(level, fixed, frame:GetChildren())
    end
  end
  local function nest(unitFrame)
    local host = available(unitFrame) and unitFrame.isNameplate and unitFrame.Health and unitFrame or nil
    if host == nestedIn then return end
    nestedIn = host
    local shown = display:IsShown()
    display:SetParent(host or WorldFrame)
    display:SetFrameStrata(host and host:GetFrameStrata() or "BACKGROUND")
    sink(host and math.max(0, host:GetFrameLevel() - 2) or 1, host ~= nil, display)
    if display.SetIgnoreParentAlpha then display:SetIgnoreParentAlpha(host ~= nil) end
    -- Inside a plate the marker takes the plate's scale, so it grows and
    -- shrinks with the icon it hugs and never has to be measured on screen
    -- (nameplate regions are restricted: the client refuses to measure them).
    if display.SetIgnoreParentScale then display:SetIgnoreParentScale(false) end
    display:SetScale(1)
    fitted, anchored, bound = nil, nil, nil
    display:SetShown(shown)
  end

  function marker:SyncTargetFade()
    local owner = _G.SquanchOnUF_Target
    if not available(owner) then display:SetAlpha(1); return end
    if self.fadeOwner ~= owner then
      self.fadeOwner = owner
      local function sync()
        if marker.fadeOwner == owner then
          -- Pass native alpha straight through, including secret alpha. The
          -- target fader owns both directions and every smooth fade step.
          display:SetAlpha(owner:GetAlpha())
        end
      end
      hooksecurefunc(owner, "SetAlpha", sync)
      if owner.SetAlphaFromBoolean then hooksecurefunc(owner, "SetAlphaFromBoolean", sync) end
    end
    display:SetAlpha(owner:GetAlpha())
  end

  local function image(parent, file, layer)
    local texture = parent:CreateTexture(nil, layer)
    texture:SetTexture(artwork .. file .. ".tga")
    texture:SetAllPoints(parent)
    texture:SetBlendMode("ADD")
    return texture
  end
  local orbit = CreateFrame("Frame", nil, display)
  orbit:SetAllPoints(display)
  orbit:EnableMouse(false)
  local pointers = image(orbit, "arrows", "OVERLAY")
  local rectangles = {}
  -- Match the original arrow centers/radial extent in its 128px artwork.
  -- Rectangles are code-native textures, with no new asset or input owner.
  for index = 1, 4 do
    -- Melee markers stay at the four cardinal points; only ranged arrows orbit.
    local rectangle = display:CreateTexture(nil, "OVERLAY")
    rectangle:SetColorTexture(1, 1, 1, 1)
    rectangle:SetBlendMode("ADD")
    rectangle:Hide()
    rectangles[index] = rectangle
  end
  local guides = {}
  local anchors = {{"RIGHT", "LEFT", 8, 0}, {"LEFT", "RIGHT", -8, 0},
    {"BOTTOM", "TOP", 0, -8}, {"TOP", "BOTTOM", 0, 8}}
  for index, edge in ipairs(anchors) do
    local guide = display:CreateTexture(nil, "ARTWORK")
    guide:SetColorTexture(1, 1, 1, 1)
    guide:SetBlendMode("ADD")
    guide:SetPoint(edge[1], display, edge[2], edge[3], edge[4])
    guides[index] = guide
  end

  -- Friendly and hostile targets share one ring: a solid line whose range
  -- marks (arrows, rectangles) are separate regions of the marker.
  local ringFrame = CreateFrame("Frame", nil, display)
  ringFrame:SetAllPoints(display)
  ringFrame:EnableMouse(false)
  -- The plate bar is translucent, so a ring behind it would show through.
  -- Each ring texture is therefore drawn as two cropped pieces, the texture
  -- above the bar and its twin below, leaving the band behind the bar empty.
  -- Texture, blend, layer, opacity and visibility are set on both through the
  -- setters below, which skip a value the pair already has; colours can be
  -- secret, so `tint` always writes and is never compared.
  local pieces = {}
  local function piece(file, sublevel)
    local texture, twin = image(ringFrame, file, "OVERLAY"), image(ringFrame, file, "OVERLAY")
    for _, region in ipairs({ texture, twin }) do
      if sublevel then region:SetDrawLayer("OVERLAY", sublevel) end
      -- Moved with the icon it hugs: neither is snapped to whole pixels, so both
      -- take the same sub-pixel position while the plate moves.
      if region.SetSnapToPixelGrid then region:SetSnapToPixelGrid(false); region:SetTexelSnappingBias(0) end
    end
    twin:Hide()
    texture.twin, texture.file, texture.blend, texture.layer, texture.shown, texture.low = twin, file, "ADD", "OVERLAY", true, false
    pieces[#pieces + 1] = texture
    return texture
  end
  local ringSize, cutOn, cutY, cutHeight, bandHealth = nil, false, 0, 0, nil
  local function layoutPiece(texture)
    local size, d = ringSize, texture.inflate or 0
    local active = cutOn and size and size > 0 or false
    local y, band = active and cutY, active and cutHeight
    if texture.laidSize == size and texture.laidInflate == d and texture.laidY == y and texture.laidBand == band then return end
    texture.laidSize, texture.laidInflate, texture.laidY, texture.laidBand = size, d, y, band
    local twin = texture.twin
    texture:ClearAllPoints()
    if active then
      local full = size + 2 * d
      local top = math.max(0, math.min(full, size / 2 + d - (y + band / 2)))
      local bottom = math.max(0, math.min(full, y - band / 2 + size / 2 + d))
      texture:SetPoint("TOPLEFT", ringFrame, "TOPLEFT", -d, d)
      texture:SetPoint("TOPRIGHT", ringFrame, "TOPRIGHT", d, d)
      texture:SetHeight(math.max(top, 0.001))
      texture:SetTexCoord(0, 1, 0, top / full)
      twin:ClearAllPoints()
      twin:SetPoint("BOTTOMLEFT", ringFrame, "BOTTOMLEFT", -d, -d)
      twin:SetPoint("BOTTOMRIGHT", ringFrame, "BOTTOMRIGHT", d, -d)
      twin:SetHeight(math.max(bottom, 0.001))
      twin:SetTexCoord(0, 1, 1 - bottom / full, 1)
      texture.low = bottom > 0
    else
      texture:SetPoint("TOPLEFT", ringFrame, "TOPLEFT", -d, d)
      texture:SetPoint("BOTTOMRIGHT", ringFrame, "BOTTOMRIGHT", d, -d)
      texture:SetTexCoord(0, 1, 0, 1)
      texture.low = false
    end
    twin:SetShown(texture.shown and texture.low)
  end
  -- One pass over the shown pieces; a piece whose size, inflation and cut are
  -- unchanged is left alone, and a hidden one is laid out when it is shown.
  local function layoutPieces()
    for index = 1, #pieces do
      if pieces[index].shown then layoutPiece(pieces[index]) end
    end
  end
  local function setShown(texture, shown)
    if texture.shown == shown then return end
    texture.shown = shown
    texture:SetShown(shown)
    if shown then layoutPiece(texture) end
    texture.twin:SetShown(shown and texture.low)
  end
  local function setFile(texture, file)
    if texture.file == file then return end
    texture.file = file
    texture:SetTexture(artwork .. file .. ".tga"); texture.twin:SetTexture(artwork .. file .. ".tga")
  end
  local function setBlend(texture, mode)
    if texture.blend == mode then return end
    texture.blend = mode
    texture:SetBlendMode(mode); texture.twin:SetBlendMode(mode)
  end
  local function setLayer(texture, layer)
    if texture.layer == layer then return end
    texture.layer = layer
    texture:SetDrawLayer(layer); texture.twin:SetDrawLayer(layer)
  end
  local function setFade(texture, opacity)
    if texture.fade == opacity then return end
    texture.fade = opacity
    texture:SetAlpha(opacity); texture.twin:SetAlpha(opacity)
  end
  local function tint(texture, red, green, blue)
    texture.tintRed = nil
    texture:SetVertexColor(red, green, blue); texture.twin:SetVertexColor(red, green, blue)
  end
  -- A colour from the settings (public numbers).
  local function setTint(texture, red, green, blue)
    if texture.tintRed == red and texture.tintGreen == green and texture.tintBlue == blue then return end
    tint(texture, red, green, blue)
    texture.tintRed, texture.tintGreen, texture.tintBlue = red, green, blue
  end
  -- Owner: every target ring is one solid line.
  local ring = piece("circle")
  -- Owner: the friendly ring is a couple of pixels thicker at the same radius. Two copies sit one
  -- physical pixel outside and inside the main line, so the mean radius holds
  -- at every ring size (a thicker texture would scale with the ring instead).
  local ringEdges = {}
  for index, direction in ipairs({ 1, -1 }) do
    local edge = piece("circle")
    edge.direction = direction
    setShown(edge, false) -- friendly icon ring only
    ringEdges[index] = edge
  end
  -- The selected plate's bar wears an additive gloss (the target overlay); the
  -- bar-look ring wears the same gloss at the same strength so the two match.
  local ringGloss = piece("ring-gloss-5", 2)
  setShown(ringGloss, false)
  -- The plate border is drawn inside the bar, over its top and bottom rows; the
  -- same tint covers the same share of the ring at its outer and inner edge.
  local ringRim = piece("ring-rim-5", 3)
  setBlend(ringRim, "BLEND")
  setShown(ringRim, false)
  local barLook, ringArt, ringWidth, shownRed, shownGreen, shownBlue = false, "circle"
  -- Mouseover glow: soft additive copies of the plain line stepping outward
  -- from the ring, in the ring's colour (as the reticle's in-range glow does).
  local ringGlows, glowLit = {}, false
  for index, strength in ipairs({ 0.35, 0.22, 0.14, 0.07 }) do
    local glow = piece("circle", -1)
    glow.strength, glow.step = strength, index
    setShown(glow, false)
    ringGlows[index] = glow
  end
  -- The cut is computed from the layout alone: the bar's height, and where
  -- the ring's anchor (the icon, or the bar itself) sits relative to the bar.
  local cutAnchor, cutDY
  local function cutBand(health)
    bandHealth, cutOn = health, false
    local host = nestedIn
    if host and available(health) and health:IsShown() then
      -- Layout numbers the plate recorded when it placed its bar and icon.
      local height = tonumber(host.npBarHeight)
      local offset = 0                         -- the ring centre above the bar centre
      if cutAnchor and cutAnchor ~= health then offset = tonumber(host.npIconRise) end
      if height and offset then cutOn, cutY, cutHeight = true, -(offset + (cutDY or 0)), height end
    end
    layoutPieces()
  end
  -- Bar look: which units take it, the ring face of the bar texture in use, and
  -- the colour the selected plate's health bar shows right now.
  local function barLookWanted()
    -- NPCs of either side keep the plain ring and its white-to-red health colour
    -- unless asked otherwise; players wear their plate bar's look.
    if marker.friendly then
      if publicQuery(UnitIsPlayer, "target") == true then return settings.friendlyBarLook ~= false end
      return settings.friendlyNpcBarLook == true
    end
    if publicQuery(UnitIsPlayer, "target") == true then return settings.hostilePlayerBarLook ~= false end
    return settings.hostileNpcBarLook == true
  end
  local faceOf = {}
  local function barFace()
    -- Plater and unknown textures take the flat ring.
    local plates, media = not Plater and suite.Nameplates, suite.Media
    local health = plates and plates.Settings and plates:Settings().health
    local path = media and type(health) == "table" and media:Resolve("statusbar", health.texture)
    if type(path) ~= "string" then return "flat" end
    local face = faceOf[path]
    if not face then
      local lower = path:lower()
      -- The client's own bar texture, the plates' default.
      face = lower:find("targetingframe[\\/]ui%-statusbar") and "default" or RING_FACES[lower:match("bar%-(%a+)%.tga$") or ""] or "flat"
      faceOf[path] = face
    end
    return face
  end
  marker.BarFace = barFace
  -- File names of the generated art, built once per face and width.
  local artFiles = {}
  local function artFile(face, width)
    local list = artFiles[face]
    if not list then list = {}; artFiles[face] = list end
    if not list[width] then list[width] = "ring-" .. face .. "-" .. width end
    return list[width]
  end
  -- The generated line width nearest the wanted one, for a ring `pixels` wide on screen.
  local function lineWidth(pixels, fitted)
    local wanted = 2.5 + (fitted and pixels > 0 and (limit(settings.friendlyThickness, 1, 0, 12) + limit(settings.barLookThickness, 1, 0, 12)) * 128 / pixels or 0)
    local width = RING_WIDTHS[1]
    for _, candidate in ipairs(RING_WIDTHS) do
      if math.abs(candidate - wanted) < math.abs(width - wanted) then width = candidate end
    end
    return width
  end
  marker.LineWidth = lineWidth
  local function barColor(plate)
    local frame = available(plate) and (plate.unitFrame or plate.UnitFrame)
    local bar = frame and (frame.Health or frame.healthBar)
    if not (available(bar) and bar.GetStatusBarColor) then return end
    -- Squanch-On keeps a name-only plate's hidden bar coloured; others may not.
    if not frame.npColorSource and not bar:IsShown() then return end
    local ok, red, green, blue = pcall(bar.GetStatusBarColor, bar)
    if not ok then return end
    if issecretvalue and (issecretvalue(red) or issecretvalue(green) or issecretvalue(blue)) then
      return true, red, green, blue, true
    end
    if type(red) == "number" and type(green) == "number" and type(blue) == "number" then
      return true, red, green, blue
    end
  end
  local function fitRingEdges()
    local scale = ringFrame:GetEffectiveScale()
    local pixel = scale and scale > 0 and PixelUtil.GetPixelToUIUnitFactor() / scale or 1
    for _, edge in ipairs(ringEdges) do
      local d = pixel * edge.direction * limit(settings.friendlyThickness, 1, 0, 12) / 2
      -- Bar look: the two dark lines touch the ring's outer and inner edge from
      -- outside (edge.border is the inflation that moves the line that far).
      if edge.border then d = edge.direction * edge.border end
      edge.inflate = d
    end
    -- Each glow line sits one more screen pixel and a half outside the ring.
    for _, glow in ipairs(ringGlows) do
      glow.inflate = (ringEdges[1].border or 0) + pixel * 1.5 * glow.step
    end
  end

