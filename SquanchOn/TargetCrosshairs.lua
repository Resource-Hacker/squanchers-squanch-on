  local function applyRange(mode)
    marker.rangeMode = mode
    marker.inRange = mode ~= nil
    pointers:SetShown(mode == "ranged" or mode == "healing")
    for index = 1, #rectangles do rectangles[index]:SetShown(mode == "melee") end
    rangeOpacity()
    -- The marks are coloured only while they show.
    if mode and paintHealth and display:IsShown() then paintHealth() end
  end
  function marker:RefreshRange()
    if not display:IsVisible() then return end
    if barLook and not ringShifted then
      -- Threat, tap and faction recolours of the plate bar reach the ring here.
      local found, red, green, blue, secret = barColor(boundPlate)
      if found and (secret or red ~= shownRed or green ~= shownGreen or blue ~= shownBlue) then
        ringColor(red, green, blue, secret)
      end
    end
    local mode
    if self.friendly then
      if healingRange() then
        mode = "healing"
      elseif publicQuery(UnitIsDeadOrGhost, "target") == false then
        local range = Plater and Plater.RangeCheckRangeFriendly
          or suite.Nameplates and suite.Nameplates:FriendlyRange() or 40
        -- Keep friendly/NPC proximity separate: it never lights healing arrows.
        local result = suite.Range and suite.Range:Within("target", range)
        if result == true or result == 1 then mode = "friendly" end
      end
    else
      mode = targetRangeMode()
    end
    if self.rangeMode ~= mode then applyRange(mode) end
  end

