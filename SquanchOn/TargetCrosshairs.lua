  -- Friendly targets: fit the ring around Plater's nameplate indicator icon
  -- (class icon when enabled, otherwise the faction emblem). Plater reuses
  -- these textures, so record which one it assigned to each plate. Squanch-On's
  -- own plates (Nameplates.lua) publish their emblem in the same
  -- plate.IconIndicators list, which the fallback in iconFit reads.
  local RING_INNER, ICON_CLEARANCE = 0.684, 1.5
  local plateIcons = setmetatable({}, { __mode = "k" })
  local iconHooks, refitQueued = false, false
  local function hookIcons()
    if iconHooks or not (Plater and Plater.AddIndicator and Plater.ClearIndicators) then return end
    iconHooks = true
    local function refit(plate)
      if plate ~= boundPlate or refitQueued then return end
      refitQueued = true
      C_Timer.After(0, function() refitQueued = false; marker:RefreshTarget() end)
    end
    hooksecurefunc(Plater, "ClearIndicators", function(plate)
      if not plate then return end
      plateIcons[plate] = nil
      refit(plate)
    end)
    hooksecurefunc(Plater, "AddIndicator", function(plate, indicator)
      local list = plate and plate.IconIndicators
      local icon = list and list[(list.Next or 1) - 1]
      local kind = indicator == "classicon" and "class"
        or (indicator == "Horde" or indicator == "Alliance") and "faction"
      if not icon or not kind then return end
      plateIcons[plate] = plateIcons[plate] or {}
      plateIcons[plate][kind] = icon
      refit(plate)
    end)
  end
  -- Ring size and centre offset for an icon of this size: `scale` is the icon's
  -- effective scale, `own` the ring's. Also the friendly mouseover ring's rule.
  local function fitSize(kind, width, height, scale, own, nested)
    -- Class tiles are square (clear their corners); faction emblems are round.
    local radius = kind == "class" and math.sqrt(width * width + height * height) / 2
      or math.max(width, height) / 2
    -- Owner: 25% tighter than the geometric fit (the emblem art has transparent padding).
    -- The emblem's art sits slightly right of and above its texture centre
    -- (measured about 4% of its size on screen); centre on the art.
    -- Squanch-On's own emblem is centred in its texture (measured): no shift.
    -- (Owner: 4% read one pixel right and 0% one pixel left on Squanch-On plates.)
    local dx = kind == "faction" and width * (nested and 0.02 or 0.04) * scale / own or 0
    local dy = kind == "faction" and height * 0.045 * scale / own or 0
    -- Owner: nine screen pixels wider than the tightened fit (5, then +4 for the solid ring).
    local grow = limit(settings.friendlyGrow, 9, -40, 80) * PixelUtil.GetPixelToUIUnitFactor() / own
    return limit(2 * (radius + ICON_CLEARANCE) * scale / own / RING_INNER * limit(settings.friendlyTighten, 0.75, 0.3, 2) + grow, baseSize, 1, 2048), dx, dy
  end
  marker.FitIcon = fitSize
  local function measured(kind, icon)
    local width = publicQuery(icon.GetWidth, icon)
    local height = publicQuery(icon.GetHeight, icon)
    local scale = publicQuery(icon.GetEffectiveScale, icon)
    local own = publicQuery(display.GetEffectiveScale, display)
    if not (width and height and scale and own) or width <= 0 or height <= 0
      or scale <= 0 or own <= 0 then return end
    return icon, fitSize(kind, width, height, scale, own, nestedIn)
  end
  local function iconFit(plate)
    if not marker.friendly or publicQuery(UnitCanAttack, "player", "target") ~= false then return end
    if settings.friendlyFit == false then return end
    local icons = plateIcons[plate]
    local class, faction = icons and icons.class, icons and icons.faction
    if not (class or faction) then
      -- The hook can miss an indicator created before it was installed or
      -- reused without a new call; fall back to the plate's first shown icon.
      local list = plate.IconIndicators
      for index = 1, list and #list or 0 do
        if available(list[index]) and list[index]:IsShown() then faction = list[index]; break end
      end
    end
    if available(class) and class:IsVisible() then return measured("class", class) end
    if available(faction) and faction:IsVisible() then return measured("faction", faction) end
  end
  -- Hostile player in bar look: the full-health colour its health shift starts
  -- from (class, else the plate bar, else white) and a cache key for its curve.
  local shiftCurves, ringShifted = {}, false
  local function shiftCurve(key, red, green, blue)
    shiftCurves[key] = shiftCurves[key] or colorCurve(red, green, blue)
    return shiftCurves[key]
  end
