-- Usage: lua5.4 tools/export_defaults.lua <SavedVariables/SquanchOn.lua> [profile] > SquanchOn/DefaultProfile.lua
-- Writes one profile of the author's saved settings (default: "Default") as the
-- addon's first-run defaults. A saved file still in the flat schema-1 shape is
-- first passed through the addon's own migration (SquanchOn/Profiles.lua), in
-- memory; the saved file is only read.
-- Diagnostics, migration receipts, import sources and per-character records
-- (which profile a character uses) are left out.
dofile(arg[1])
local root = assert(SquanchOnDB, 'SquanchOnDB missing')

-- Load Profiles.lua for its migration and receipt classification. It needs
-- three game functions at load; none of them reads anything from this machine.
local ns = {}
CreateFrame = function() return { RegisterEvent = function() end, SetScript = function() end } end
UnitName, GetRealmName = function() end, function() end
local here = arg[0]:match('^(.*)[/\\][^/\\]*$') or '.'
assert(loadfile(here .. '/../SquanchOn/Profiles.lua'))('SquanchOn', ns)
if type(root.schema) ~= 'number' or root.schema < 2 then root = ns.Profiles.Migrate(root) end
local name = arg[2] or 'Default'
local db = assert(root.profiles[name], 'no profile named ' .. name)
local receipts = root.global and root.global.receipts or {}

-- Tables that ship. Not exported: itemWindowSizing and minimapItemSizing
-- (measured per install; their presence skips the one-time icon match).
local tables = { unitFrames = true, tooltipImport = true, layout = true, nativeWindowImport = true,
  appearance = true, nameplateIndicators = true, targetCrosshairs = true, camera = true, screen = true }
-- The camera settings ship; its takeover records do not. The import receipt and
-- the retired framing record name the author's DynamicCam profiles, and a
-- missing receipt is what lets a new install import its own DynamicCam profile.
if type(db.camera) == 'table' then
  for _, key in ipairs({ 'receipt', 'previous', 'legacyFraming', 'combatDeferred' }) do db.camera[key] = nil end
end
-- Of the appearance receipts only two describe the shipped data itself: the
-- bars are already centred, and a new install has no earlier font scale to restore.
if type(db.appearance) == 'table' then
  db.appearance = { centeredBars30020261110 = db.appearance.centeredBars30020261110 and true or nil,
    previousSizeRestored = db.appearance.previousSizeRestored and true or nil }
end
-- Scalar receipts ship unless they record this install's own history; a first
-- run files them under the account-wide receipts again.
local skip = { loadedVersion = true, chatTimestampRestored = true, nativeReturnRevision = true,
  targetCrosshairsMigration = true, seedPending = true }
local function local_history(k) return skip[k] or k:match('Original') or k:match('Previous') end

local function key(k)
  if type(k) == 'number' then return '[' .. (math.type(k) == 'integer' and tostring(k) or string.format('%.17g', k)) .. ']' end
  if k:match('^[%a_][%w_]*$') then return k end
  return '[' .. string.format('%q', k) .. ']'
end
local function value(v, depth)
  local kind = type(v)
  if kind == 'table' then
    local keys = {}
    for k in pairs(v) do if type(k) == 'string' or type(k) == 'number' then keys[#keys + 1] = k end end
    table.sort(keys, function(a, b)
      if type(a) == type(b) then return a < b end
      return type(a) == 'number'
    end)
    local parts = {}
    for _, k in ipairs(keys) do
      local child = value(v[k], depth + 1)
      if child then parts[#parts + 1] = key(k) .. '=' .. child end
    end
    return '{' .. table.concat(parts, ',') .. '}'
  elseif kind == 'number' then
    if v ~= v or v == math.huge or v == -math.huge then return nil end
    if math.type(v) == 'integer' then return tostring(v) end
    local short = string.format('%.6g', v)
    return tonumber(short) == v and short or string.format('%.17g', v)
  elseif kind == 'string' then return string.format('%q', v):gsub('\\\n', '\\n')
  elseif kind == 'boolean' then return tostring(v) end
end
local out = {}
for k, v in pairs(db) do
  if type(k) == 'string' and not local_history(k) then
    if type(v) == 'table' then if tables[k] then out[k] = v end
    else out[k] = v end
  end
end
for k, v in pairs(receipts) do
  if type(k) == 'string' and type(v) ~= 'table' and not local_history(k) and out[k] == nil then out[k] = v end
end
local names = {}
for k in pairs(out) do names[#names + 1] = k end
table.sort(names)
io.write('-- SPDX-License-Identifier: MIT\n-- Generated by tools/export_defaults.lua: the author\'s layout as one profile,\n-- used for a first run, a new profile and a profile reset. Edit in game, not here.\n')
io.write('local _, ns = ...\nns.DefaultProfile = {\n')
for _, k in ipairs(names) do io.write(key(k), '=', value(out[k], 0), ',\n') end
io.write('}\n')
